import type { EmailHeaders } from "@/utils/spam-detector";

// Pure classification for inbound offer mail. Deliberately free of prisma and
// of the Graph client so it can be unit-tested against captured message
// fixtures — the bounce detector will want the same treatment.

// Offer emails carry "[RCOFR-<12 hex>]" in the subject; replies keep it as
// "Re: … [RCOFR-…]", letting us correlate an inbound message to the send.
const OFFER_TOKEN_RE = /\[(RCOFR-[0-9A-Fa-f]{12})\]/;

export function extractOfferReplyToken(
  subject: string | undefined | null,
): string | null {
  if (!subject) {
    return null;
  }
  const match = OFFER_TOKEN_RE.exec(subject);
  return match ? match[1].toUpperCase() : null;
}

// A bounce quotes the original subject, so "Undeliverable: … [RCOFR-…]" and an
// out-of-office "Automatic reply: … [RCOFR-…]" both carry the token. Neither is
// the client replying.
//
// Deliberately structural rather than sender-based: the bounce for a rejected
// Gmail mailbox is generated by Exchange Online, not Google, and EXO's DSN
// sender varies by tenant configuration (postmaster@, or the
// MicrosoftExchange329e71ec…@ system mailbox). Headers are stable; senders are
// not. Absent headers mean "no signal", not "not machine-generated".
export function isMachineGenerated(headers: EmailHeaders): boolean {
  const { autoSubmitted, returnPath, contentType } = headers;

  // RFC 3834: anything other than "no" means the message was generated
  // automatically. Out-of-office replies set this even though they come from
  // the client's own address, so it must be checked before any sender match.
  if (autoSubmitted && autoSubmitted.trim().toLowerCase() !== "no") {
    return true;
  }
  // RFC 3464: a delivery status notification carries an empty return path.
  if (returnPath && returnPath.replace(/\s/g, "") === "<>") {
    return true;
  }
  if (contentType?.toLowerCase().includes("report-type=delivery-status")) {
    return true;
  }
  return false;
}
